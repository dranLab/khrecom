MAPUNITTABLE* mapUnitTableSearch(const ZONEPARTS* parts) {
    MAPUNITTABLE** ppTbl;
    MAPUNITTABLE* pItem;

    for (INT i = 0; (ppTbl = _pMapUnitTableTbl[i]) != NULL; i++) {
        for (INT j = 0; (pItem = ppTbl[j]) != NULL; j++) {
            if (pItem->id.ui != 0 && parts->effectId == pItem->id.ui) {
                return pItem;
            }
        }
    }
    return NULL;
}

