#!/usr/bin/env python3
"""Import the symbols left in the game's ELF into a splat symbol file.

Writes config/<VERSION>/elf_symbol_addrs.txt (regenerate it any time; put manual
symbols into symbol_addrs.txt instead) and adds it to the splat yaml.

- functions get `type:func`, everything gets `size:` when the ELF knows it
- names that occur more than once (file-local statics) get an `_<ADDR>` suffix,
  because the code is still one big assembly file
- compiler markers, linker-defined absolute symbols and VU microcode labels are skipped

Usage:
    python3 tools/import_symbols.py SLUS_217.99
"""

import argparse
import re
import sys
from collections import Counter
from pathlib import Path

import yaml
from elftools.elf.elffile import ELFFile

ROOT = Path(__file__).resolve().parent.parent
IMAGE_SECTIONS = {".text", ".data", ".sndata", ".rodata", ".sdata", ".sbss", ".bss"}
SKIP_NAMES = re.compile(r"^(gcc2_compiled\.|__gnu_compiled_c(plusplus)?|_gp)$")
BIND_RANK = {"STB_GLOBAL": 0, "STB_WEAK": 1, "STB_LOCAL": 2}
TYPE_RANK = {"STT_FUNC": 0, "STT_OBJECT": 0, "STT_NOTYPE": 1}


def collect(elf: ELFFile) -> list[dict]:
    sections = list(elf.iter_sections())
    by_addr: dict[int, dict] = {}
    for sym in elf.get_section_by_name(".symtab").iter_symbols():
        typ, bind, shndx = sym["st_info"]["type"], sym["st_info"]["bind"], sym["st_shndx"]
        if isinstance(shndx, str) or not sym.name or SKIP_NAMES.match(sym.name):
            continue  # SHN_ABS/SHN_UNDEF: linker-defined or undefined
        section = sections[shndx].name
        if section not in IMAGE_SECTIONS or typ not in TYPE_RANK:
            continue
        # Local NOTYPE symbols are labels inside hand-written asm (md*_dma, EER*, ...); naming them would split functions.
        if typ == "STT_NOTYPE" and bind == "STB_LOCAL":
            continue
        entry = {
            "name": sym.name,
            "addr": sym["st_value"],
            "size": sym["st_size"],
            "func": section == ".text" and typ in ("STT_FUNC", "STT_NOTYPE"),
            "rank": (TYPE_RANK[typ], BIND_RANK[bind], -sym["st_size"]),
        }
        # One name per address: prefer typed, then global over weak over local, then the sized one.
        current = by_addr.get(entry["addr"])
        if current is None or entry["rank"] < current["rank"]:
            by_addr[entry["addr"]] = entry
    return sorted(by_addr.values(), key=lambda e: e["addr"])


def write_symbols(entries: list[dict], out: Path, elf_name: str) -> None:
    counts = Counter(e["name"] for e in entries)
    lines = [
        f"// Generated by tools/import_symbols.py from {elf_name} - do not edit, add manual symbols to symbol_addrs.txt.",
    ]
    for e, nxt in zip(entries, entries[1:] + [None]):
        name = e["name"] if counts[e["name"]] == 1 else f"{e['name']}_{e['addr']:08X}"
        attrs = []
        if e["func"]:
            attrs.append("type:func")
        # Hand-written asm (crt0, exception handlers) sometimes has sizes that run into the next symbol.
        if e["size"] and (nxt is None or e["addr"] + e["size"] <= nxt["addr"]):
            attrs.append(f"size:0x{e['size']:X}")
        lines.append(f"{name} = 0x{e['addr']:08X};" + (f" // {' '.join(attrs)}" if attrs else ""))
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def register_in_yaml(splat_yaml: Path, symbols_file: str) -> bool:
    text = splat_yaml.read_text(encoding="utf-8")
    if symbols_file in text:
        return False
    marker = "  symbol_addrs_path:\n"
    if marker not in text:
        sys.exit(f"error: no symbol_addrs_path list in {splat_yaml}")
    text = text.replace(marker, f"{marker}    - {symbols_file}\n", 1)
    splat_yaml.write_text(text, encoding="utf-8", newline="\n")
    return True


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("version", help="folder name under config/")
    args = parser.parse_args()

    cfg_dir = ROOT / "config" / args.version
    build_cfg = yaml.safe_load((cfg_dir / "build.yaml").read_text(encoding="utf-8"))
    elf_path = ROOT / build_cfg["elf"]
    with elf_path.open("rb") as f:
        entries = collect(ELFFile(f))

    out = cfg_dir / "elf_symbol_addrs.txt"
    write_symbols(entries, out, elf_path.name)
    funcs = sum(e["func"] for e in entries)
    print(f"wrote {len(entries)} symbols ({funcs} functions, {len(entries) - funcs} data) to {out.relative_to(ROOT)}")
    if register_in_yaml(cfg_dir / f"{args.version}.yaml", out.relative_to(ROOT).as_posix()):
        print(f"added it to symbol_addrs_path in {args.version}.yaml")


if __name__ == "__main__":
    main()
