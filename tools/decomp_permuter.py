#!/usr/bin/env python3
"""Run decomp-permuter (tools/decomp-permuter, a git submodule) on one function of a C unit.

decomp-permuter parses the function with pycparser and applies many AST-level randomizations (temporaries, type
casts, reordering, if/else forms, ...); it finds register and scheduling fixes that tools/permuter.py's textual
mutations do not. It only reads C: for .cpp units use tools/permuter.py.

This script prepares build/decomp-permuter/<function>/ the way decomp-permuter expects it and starts it:
    base.c         the unit preprocessed with the unit's own command (a parked #if 0 draft switched on)
    compile.sh     the unit's own build pipeline (compiler, ee_asm_compat.py, assembler) for one candidate
    target.o       the original object of the unit (build/<version>/expected/units/<unit>.o)
    settings.toml  function name, gcc weights, and an objdump that disassembles only the function
Improvements land in build/decomp-permuter/<function>/output-<score>-<n>/ (source.c, diff.txt). Its scores are
its own (weighted by the kind of difference), not funcdiff's line count: put a result's function into the source and
check it with tools/funcdiff.py. Randomizations can change the program's meaning: read every diff before adopting.

Usage:
    .venv/bin/python tools/decomp_permuter.py lib/kprintf2 ftoi --minutes 15 -j 16
    .venv/bin/python tools/decomp_permuter.py lib/kprintf2 ftoi --setup-only   # then edit base.c (PERM_* macros)
    .venv/bin/python tools/decomp_permuter.py lib/kprintf2 ftoi --resume       # run on the existing directory
Arguments after `--` go to decomp-permuter (e.g. `-- --stack-diffs`).
"""

import argparse
import difflib
import json
import os
import re
import shlex
import shutil
import signal
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PERMUTER = ROOT / "tools" / "decomp-permuter" / "permuter.py"


def objdump(func: str, obj: str) -> None:
    """The function's disassembly with only the relocations inside it (the scorer reads the whole output)."""
    out = subprocess.run(["mips-linux-gnu-objdump", "-drz", "-m", "mips:5900", f"--disassemble={func}", obj],
                         capture_output=True, text=True, check=True).stdout.splitlines()
    addrs = [int(m.group(1), 16) for line in out for m in [re.match(r"\s*([0-9a-f]+):\t[0-9a-f]{8}\s", line)] if m]
    lo, hi = (min(addrs), max(addrs) + 4) if addrs else (0, 0)
    for line in out:
        m = re.match(r"\s*([0-9a-f]+): R_MIPS", line)
        if not (m and not lo <= int(m.group(1), 16) < hi):
            print(line)


def compile_script(command: str, unit: str, source: Path, obj: str) -> str:
    """compile.sh <in.c> -o <out.o>: the unit's command with the candidate as input and private outputs."""
    rel = str(source.relative_to(ROOT))
    steps = []
    for step in command.split(" && "):
        if step.startswith("sed -i"):  # the .d file fixup
            continue
        step = re.sub(r"\s-Wp,-MD,\S+", "", step)
        step = re.sub(r" -R \S+", "", step)  # keep data sections: a draft's literals would leave dangling relocs
        step = step.replace(obj + ".gcc.s", '"$T/out.gcc.s"').replace(obj + ".s", '"$T/out.s"').replace(obj, '"$OUT"')
        if not steps:  # the compiler reads the candidate; ee_asm_compat.py --source keeps the real file
            step = re.sub(r"(?<=\s)" + re.escape(rel) + r"(?=\s|$)", '"$IN"', step)
            # quoted includes of the unit's own directory still resolve (the candidate lives elsewhere)
            step = step.replace(" -I src", f" -I {source.parent.relative_to(ROOT)} -I src", 1)
        steps.append(step)
    return ("#!/bin/bash\n"
            f"# compile.sh <in.c> -o <out.o>: the build of {unit} for one candidate (generated by decomp_permuter.py)\n"
            "set -e\n"
            'IN=$(realpath "$1"); OUT=$(realpath -m "$3"); T=$(mktemp -d -p "$(dirname "$OUT")")\n'
            'trap \'rm -rf "$T"\' EXIT\n'
            f"cd {ROOT}\n"
            'export TMPDIR="$T"\n'
            + "\n".join(steps) + "\n")


def preprocess(command: str, source: Path, text: str, out: Path, workdir: Path) -> None:
    """The unit's compile step with -E: the enabled draft, preprocessed exactly as the build sees it."""
    cc = command.split(" && ")[0]
    rel = str(source.relative_to(ROOT))
    tmp = workdir / ("unit" + source.suffix)
    tmp.write_text(text, encoding="latin-1")
    cc = re.sub(r"\s-Wp,-MD,\S+", "", cc)
    cc = re.sub(r"\s-S(?=\s)", " -E", cc, count=1)
    cc = re.sub(r"\s-o\s+\S+", f" -o {out}", cc, count=1)
    cc = re.sub(r"(?<=\s)" + re.escape(rel) + r"(?=\s|$)", str(tmp), cc)
    cc = cc.replace(" -I src", f" -I {source.parent.relative_to(ROOT)} -I src", 1)
    r = subprocess.run(cc, shell=True, cwd=ROOT, capture_output=True, text=True,
                       env={**os.environ, "TMPDIR": str(workdir)})
    tmp.unlink()
    if r.returncode or not out.exists():
        sys.exit("preprocessing failed:\n" + (r.stdout + r.stderr)[-2000:])


def starts_statement(text: str, pos: int) -> bool:
    """Whether the code at pos begins a statement: after ; { } or a label's :, or after the ) of an if/while/for/
    switch condition (not after a declarator's ), as in `void f(void) __asm__("name");`)."""
    before = text[:pos].rstrip()
    if not before or before[-1] in ";{}:":
        return True
    if before[-1] != ")":
        return False
    depth, j = 0, len(before) - 1
    while j >= 0:
        depth += {")": 1, "(": -1}.get(before[j], 0)
        if depth == 0:
            break
        j -= 1
    return re.search(r"\b(if|while|for|switch)\s*$", before[:max(j, 0)]) is not None


def ignore_asm(text: str) -> str:
    """Every asm statement as PERM_IGNORE(...): pycparser rejects VU0 asm with expression operands."""
    out, i = [], 0
    for m in re.finditer(r"\b__asm__\s*(?:__volatile__|volatile)?\s*\(", text):
        if m.start() < i or not starts_statement(text, m.start()):
            continue  # not a statement (a register asm declaration, an asm label)
        j, depth = m.end(), 1
        while depth:
            c = text[j]
            if c == '"':
                j += 1
                while text[j] != '"':
                    j += 2 if text[j] == "\\" else 1
            elif c == "(":
                depth += 1
            elif c == ")":
                depth -= 1
            j += 1
        k = re.match(r"\s*;", text[j:])
        if not k:  # an asm label or an asm inside an expression: leave it to pycparser
            continue
        end = j + k.end()
        out += [text[i:m.start()], "PERM_IGNORE(", text[m.start():end], ")"]
        i = end
    return "".join(out + [text[i:]])


def setup(unit: str, func: str, workdir: Path) -> None:
    import yaml
    sys.path.insert(0, str(ROOT / "tools"))
    from permuter import build_command, definition_pattern, enable_draft, find_function  # (not loaded by the per-candidate --objdump)
    version = sorted(p.name for p in (ROOT / "config").iterdir() if (p / f"{p.name}.yaml").exists())[0]
    build = yaml.safe_load((ROOT / "config" / version / f"{version}.yaml").read_text())["options"]["build_path"]
    source = ROOT / "src" / f"{unit}.c"
    if not source.exists():
        sys.exit(f"{source.relative_to(ROOT)} not found: decomp-permuter only parses C (for .cpp: tools/permuter.py)")
    pattern = definition_pattern(func, None)  # C: no class qualifier
    text = enable_draft(source.read_text(encoding="latin-1"), pattern, func)
    start, end = find_function(text, pattern)
    if re.search(r"INCLUDE_ASM\([^)]*,\s*" + re.escape(func) + r"\s*\)", text[:start] + text[end:]):
        sys.exit(f"{func} is still INCLUDE_ASM'd outside its draft")
    obj = f"{build}/src/{unit}.o"
    expected = ROOT / build / "expected" / "units" / f"{unit}.o"
    subprocess.run(["ninja", str(expected.relative_to(ROOT))], cwd=ROOT, check=True, capture_output=True)
    command = build_command(obj)

    shutil.rmtree(workdir, ignore_errors=True)
    workdir.mkdir(parents=True)
    preprocess(command, source, text, workdir / "base.c", workdir)
    (workdir / "compile.sh").write_text(compile_script(command, unit, source, obj))
    (workdir / "compile.sh").chmod(0o755)
    shutil.copy(expected, workdir / "target.o")
    objdump_cmd = shlex.join([sys.executable, str(Path(__file__).resolve()), "--objdump", func])
    (workdir / "settings.toml").write_text(f'func_name = "{func}"\ncompiler_type = "gcc"\n'
                                           f"objdump_command = {json.dumps(objdump_cmd)}\n")
    test = workdir / "base.o"
    r = subprocess.run([str(workdir / "compile.sh"), str(workdir / "base.c"), "-o", str(test)],
                       capture_output=True, text=True)
    if r.returncode or not test.exists():
        sys.exit("base.c does not compile with compile.sh:\n" + (r.stdout + r.stderr)[-2000:])
    test.unlink()
    base = workdir / "base.c"  # what decomp-permuter compiles is base.c after its PERM_* expansion
    shutil.copy(base, workdir / "base_unwrapped.c")  # compilable as is (the report scores it)
    base.write_text(ignore_asm(base.read_text(encoding="latin-1")), encoding="latin-1")
    print(f"set up {workdir.relative_to(ROOT)}")


def run(workdir: Path, minutes: float, jobs: int, extra: list[str]) -> None:
    cmd = [sys.executable, str(PERMUTER), str(workdir), "-j", str(jobs), "--stop-on-zero", "--best-only"] + extra
    p = subprocess.Popen(cmd, cwd=PERMUTER.parent, start_new_session=True)  # own group: -j forks worker processes

    def stop() -> None:
        try:
            p.send_signal(signal.SIGINT)  # Ctrl-C for the main process; the workers are killed with the group
            p.wait(timeout=10)
        except subprocess.TimeoutExpired:
            os.killpg(p.pid, signal.SIGKILL)
            p.wait()
        except ProcessLookupError:
            pass

    stopped = False
    try:
        p.wait(timeout=minutes * 60)
    except (subprocess.TimeoutExpired, KeyboardInterrupt):
        stopped = True
        stop()
    finally:
        try:
            os.killpg(p.pid, signal.SIGKILL)  # leftover workers
        except ProcessLookupError:
            pass
    if not stopped and p.returncode:
        sys.exit(f"decomp-permuter failed (exit {p.returncode}). A syntax error in base.c: wrap the construct in "
                 "PERM_IGNORE(...) (--setup-only, edit base.c, then --resume)")
    report(workdir)


def line_score(workdir: Path, func: str, src: Path) -> int | None:
    """tools/permuter.py's score of one candidate: differing instruction lines (+4 per instruction of size)."""
    sys.path.insert(0, str(ROOT / "tools"))
    from permuter import functions, disassemble, normalize
    obj = workdir / "rescore.o"
    r = subprocess.run([str(workdir / "compile.sh"), str(src), "-o", str(obj)], capture_output=True, text=True)
    if r.returncode or not obj.exists():
        return None
    target, ours = functions(workdir / "target.o")[func], functions(obj).get(func)
    try:
        if ours is None:
            return None
        if target.difference(ours) is None:
            return 0
        a = normalize(disassemble(workdir / "target.o", func, len(target.data)))
        b = normalize(disassemble(obj, func, len(ours.data)))
        sm = difflib.SequenceMatcher(None, a, b, autojunk=False)
        diff = sum(max(i2 - i1, j2 - j1) for op, i1, i2, j1, j2 in sm.get_opcodes() if op != "equal")
        return max(1, diff + 4 * (abs(len(ours.data) - len(target.data)) // 4))
    finally:
        obj.unlink(missing_ok=True)


def permuter_base(workdir: Path, func: str) -> Path | None:
    """base.c as decomp-permuter compiles its unrandomized base: preprocessed, PERM_* expanded and printed by
    pycparser, one statement per line. Its outputs have that layout too, and with GNU as the -g line labels decide
    delay slots, so the outputs are compared with this, not with base.c's own layout."""
    out = workdir / "base_permuter.c"
    code = (f"import sys; sys.path.insert(0, {str(PERMUTER.parent)!r})\n"
            "from src.preprocess import preprocess\n"
            "from src.perm.parse import perm_parse\n"
            "from src.perm.eval import perm_evaluate_one\n"
            "from src.candidate import Candidate\n"
            "from src.helpers import get_default_randomization_weights\n"
            f"src, st = perm_evaluate_one(perm_parse(preprocess({str(workdir / 'base.c')!r})))\n"
            f"cand = Candidate.from_source(src, st, {func!r}, get_default_randomization_weights('gcc'), rng_seed=0)\n"
            f"open({str(out)!r}, 'w').write(cand.get_source())\n")
    r = subprocess.run([sys.executable, "-c", code], cwd=PERMUTER.parent, capture_output=True, text=True)
    return out if r.returncode == 0 and out.exists() else None


def report(workdir: Path, count: int = 5) -> None:
    """The best outputs, rescored in differing lines (decomp-permuter's own scores weigh kinds of differences)."""
    func = re.search(r'func_name = "([^"]+)"', (workdir / "settings.toml").read_text()).group(1)
    base = line_score(workdir, func, workdir / "base_unwrapped.c")
    pbase_c = permuter_base(workdir, func)
    pbase = line_score(workdir, func, pbase_c) if pbase_c else None
    outs = sorted(workdir.glob("output-*"), key=lambda d: (int(d.name.split("-")[1]), -d.stat().st_mtime))[:count]

    def lines(n: int | None) -> str:
        return "does not compile" if n is None else f"{n} lines differ"

    print(f"\nbase.c: {lines(base)} in its own layout, {lines(pbase)} as decomp-permuter compiles it "
          "(the outputs' layout: compare them with this)")
    if not outs:
        print("no improvement")
    for d in outs:
        n = line_score(workdir, func, d / "source.c")
        gain = f" ({n - pbase:+d} against the permuter's base)" if n is not None and pbase is not None else ""
        print(f"{d.relative_to(ROOT)}/diff.txt: score {d.name.split('-')[1]}, {lines(n)}{gain}")
    print("an output's gain only counts once it holds in the real source (tools/funcdiff.py)")


def main() -> None:
    if len(sys.argv) > 1 and sys.argv[1] == "--objdump":
        objdump(sys.argv[2], sys.argv[-1])
        return
    argv, extra = (sys.argv[1:], [])
    if "--" in argv:
        i = argv.index("--")
        argv, extra = argv[:i], argv[i + 1:]
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("unit")
    ap.add_argument("function")
    ap.add_argument("--minutes", type=float, default=15)
    ap.add_argument("-j", "--jobs", type=int, default=16)
    ap.add_argument("--setup-only", action="store_true", help="only write the directory")
    ap.add_argument("--resume", action="store_true", help="run on the existing directory (keeps edits to base.c)")
    ap.add_argument("--report", action="store_true", help="only rescore the existing directory's best outputs")
    args = ap.parse_args(argv)
    workdir = ROOT / "build" / "decomp-permuter" / args.function
    if args.report:
        report(workdir)
        return
    if not (args.resume and (workdir / "base.c").exists()):
        setup(args.unit, args.function, workdir)
    if not args.setup_only:
        t = time.time()
        run(workdir, args.minutes, args.jobs, extra)
        print(f"ran {(time.time() - t) / 60:.1f} min")


if __name__ == "__main__":
    main()
