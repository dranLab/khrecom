#!/usr/bin/env python3
"""Split .text into the original source files using the ELF's .mdebug info.

Object boundaries come from the gcc2_compiled. label gcc puts at the start of
every object (also those built without debug info) plus asm files with
procedure entries; names come from the .mdebug file descriptors at those
addresses. Code after an object's last function is hand-written asm (e.g.
expand.s). This writes one splat `asm` subsegment per object into the yaml,
between marker comments, replacing the single `.text` subsegment.

Objects without debug info are named lib/nodebug/<first symbol>.

Paths: c:/KHCOM/MainApp/<path>.cpp -> <path>, everything else (Sony SDK, libgcc)
-> lib/<path without ../ prefixes>.

Usage:
    python3 tools/split_text.py SLUS_217.99 --dry-run   # report only
    python3 tools/split_text.py SLUS_217.99
"""

import argparse
import re
import sys
from collections import Counter
from dataclasses import dataclass
from pathlib import Path, PurePosixPath

import yaml
from elftools.elf.elffile import ELFFile

import mdebug

ROOT = Path(__file__).resolve().parent.parent
GAME_ROOT = "c:/KHCOM/MainApp/"
COMPILER_MARKERS = {"gcc2_compiled.", "__gnu_compiled_c", "__gnu_compiled_cplusplus"}
PROC_TYPES = {mdebug.ST_PROC, mdebug.ST_STATICPROC}
BEGIN = "      # begin .text, generated by tools/split_text.py"
END = "      # end .text"


@dataclass
class Unit:
    start: int
    source: str  # source path from .mdebug, or "" for code linked without debug info
    first_symbol: str


def defined_procs(sf: mdebug.SourceFile, lo: int, hi: int) -> list[int]:
    return [s.value for s in sf.symbols if s.sc == mdebug.SC_TEXT and s.st in PROC_TYPES and lo <= s.value < hi]


def split_name(unit: Unit) -> str:
    if not unit.source:
        return "lib/nodebug/" + re.sub(r"[^\w.+-]", "_", unit.first_symbol)
    path = unit.source.replace("\\", "/")
    if path.lower().startswith(GAME_ROOT.lower()):
        rel = path[len(GAME_ROOT):]
    else:
        rel = "lib/" + "/".join(p for p in PurePosixPath(re.sub(r"^[a-zA-Z]:/", "", path)).parts
                                if p not in ("..", ".", "/"))
    return re.sub(r"[^\w/.+-]", "_", str(PurePosixPath(rel).with_suffix("")))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("version", help="folder name under config/")
    parser.add_argument("--dry-run", action="store_true", help="print the split without changing the yaml")
    args = parser.parse_args()

    cfg_dir = ROOT / "config" / args.version
    splat_yaml = cfg_dir / f"{args.version}.yaml"
    build_cfg = yaml.safe_load((cfg_dir / "build.yaml").read_text(encoding="utf-8"))
    elf_path = ROOT / build_cfg["elf"]

    with elf_path.open("rb") as f:
        elf = ELFFile(f)
        text = elf.get_section_by_name(".text")
        text_start, text_end, text_offset = text["sh_addr"], text["sh_addr"] + text["sh_size"], text["sh_offset"]
        first_load = min(s["sh_offset"] for s in elf.iter_sections() if s["sh_flags"] & 2 and s["sh_type"] != "SHT_NOBITS")
        # Functions plus global NOTYPE symbols (hand-written asm such as ExpandData__FPUcT0).
        symtab = [s for s in elf.get_section_by_name(".symtab").iter_symbols()
                  if text_start <= s["st_value"] < text_end and s.name]
    # Functions plus other code labels (hand-written asm such as ExpandData__FPUcT0 or draw_ws.s's md0_* labels).
    text_syms = sorted((s["st_value"], s["st_size"], s.name) for s in symtab
                       if s["st_info"]["type"] in ("STT_FUNC", "STT_NOTYPE") and s.name.isprintable()
                       and s.name not in COMPILER_MARKERS and not s.name.startswith("$"))
    size_of = {a: size for a, size, _ in text_syms}
    # gcc emits a gcc2_compiled. label at the start of every object it compiles: the ground truth for C/C++ units.
    object_starts = {s["st_value"] for s in symtab if s.name == "gcc2_compiled."}

    files = mdebug.read_mdebug(elf_path)
    defined = {}  # function address -> index of the file descriptor defining it (headers included)
    for sf in files:
        for a in defined_procs(sf, text_start, text_end):
            defined.setdefault(a, sf.index)

    # Objects start at gcc2_compiled. markers (also for objects without debug info) and at asm files with procedure
    # entries. A source with code but no marker at its address was #included into another file (mm.c into mpc.c).
    by_start: dict[int, mdebug.SourceFile] = {}
    included = []
    for sf in files:
        if sf.name.endswith(".h") or not defined_procs(sf, text_start, text_end):
            continue
        if sf.adr in object_starts or sf.name.endswith(".s"):
            by_start.setdefault(sf.adr, sf)
        else:
            included.append(sf.name)
    starters = {sf.index for sf in by_start.values()}

    # Data-only objects have their marker in the previous object's padding: only cut where code follows.
    cuts = sorted(object_starts | set(by_start) | {text_start})
    has_code = lambda lo, hi: any(lo <= a < hi for a, _, _ in text_syms)
    cuts = [c for c, nxt in zip(cuts, cuts[1:] + [text_end]) if c == text_start or has_code(c, nxt)]

    units: list[Unit] = []
    bounds = cuts + [text_end]
    for lo, hi in zip(bounds, bounds[1:]):
        sf = by_start.get(lo)
        units.append(Unit(lo, sf.name if sf else "", next((n for a, _, n in text_syms if lo <= a < hi), "")))
        if sf is None:
            continue
        # Code after the last function of a debug-info object comes from an asm file without procedure entries
        # (expand.s). Its descriptor's address is unreliable, so start right after the last function, 8-aligned.
        end = max(a + size_of.get(a, 0) for a in defined if lo <= a < hi)
        gap = [(a, n) for a, _, n in text_syms if end <= a < hi and a not in defined]
        if gap:
            following = next((i for i in range(sf.index + 1, len(files)) if i in starters), len(files))
            asm_files = [f.name for f in files[sf.index + 1:following] if f.name.endswith(".s")]
            units.append(Unit((end + 7) & ~7, asm_files[0] if asm_files else "", gap[0][1]))

    # Cross-check: functions of each object's own descriptor must lie inside that object's unit.
    unit_bounds = [u.start for u in units] + [text_end]
    unit_at = lambda a: next(u for u, lo, hi in zip(units, unit_bounds, unit_bounds[1:]) if lo <= a < hi)
    problems = [(hex(a), files[i].name) for a, i in defined.items()
                if i in starters and unit_at(a).source != files[i].name]

    names = [split_name(u) for u in units]
    counts = Counter(names)
    for i, u in enumerate(units):
        if counts[names[i]] > 1:  # e.g. libgcc2.c is compiled once per helper function
            names[i] = f"{names[i]}_{u.first_symbol}" if u.first_symbol else f"{names[i]}_{u.start:08X}"
    if len(set(names)) != len(names):
        sys.exit("error: duplicate subsegment names remain")

    rom = lambda vram: text_offset - first_load + (vram - text_start)
    lines = [BEGIN] + [f"      - [0x{rom(u.start):06X}, asm, {n}] # {u.source or 'no debug info'}"
                       for u, n in zip(units, names)] + [END]

    nodebug = [n for n in names if n.startswith("lib/nodebug/")]
    print(f"{len(files)} file descriptors -> {len(units)} units: "
          f"{sum(not n.startswith('lib/') for n in names)} game, "
          f"{sum(n.startswith('lib/') for n in names) - len(nodebug)} library, {len(nodebug)} without debug info")
    print(f"{len(object_starts)} object markers; included sources (no object of their own): {included}")
    print(f"{len(defined)} functions in .mdebug, {len(problems)} outside their object")
    for item in problems[:10]:
        print("  outside:", item)
    for u, n in zip(units, names):
        if not u.source or u.source.endswith(".s"):
            print(f"  {u.start:#010x} {n}")
    if args.dry_run:
        print("\n".join(lines[:8] + ["      ..."] + lines[-4:]))
        return
    if problems:
        sys.exit("error: refusing to write a split with functions outside their object")

    text_yaml = splat_yaml.read_text(encoding="utf-8")
    block = re.compile(rf"^{re.escape(BEGIN)}\n.*?^{re.escape(END)}\n", re.MULTILINE | re.DOTALL)
    single = re.compile(r"^      - \[0x000000, asm, [^\]]+\] # \.text\n", re.MULTILINE)
    new_block = "\n".join(lines) + "\n"
    if block.search(text_yaml):
        text_yaml = block.sub(lambda _: new_block, text_yaml, count=1)
    elif single.search(text_yaml):
        text_yaml = single.sub(lambda _: new_block, text_yaml, count=1)
    else:
        sys.exit("error: can't find the .text subsegment in the yaml")
    splat_yaml.write_text(text_yaml, encoding="utf-8", newline="\n")
    print(f"wrote {len(units)} .text subsegments to {splat_yaml.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
